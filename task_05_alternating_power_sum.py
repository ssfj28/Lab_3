# Задание 5. Сумма 1 - A + A^2 - A^3 + ... ± A^N.
# Условный оператор не используется: каждый следующий член получается
# умножением предыдущего на -A.

a = float(input("Введите вещественное число A: "))
n = int(input("Введите целое положительное число N: "))

term = 1.0
result = 1.0
for _ in range(n):
    term *= -a
    result += term

print("Значение выражения:", f"{result:.10g}")
