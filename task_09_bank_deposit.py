# Задание 9. Определение количества месяцев, необходимых для того,
# чтобы вклад 1000 рублей превысил 1100 рублей.

p = float(input("Введите процент P (0 < P < 25): "))

amount = 1000.0
months = 0
while amount <= 1100:
    amount += amount * p / 100
    months += 1

print("Количество месяцев:", months)
print("Итоговый размер вклада:", f"{amount:.2f}", "руб.")
